"""
Módulo de Internacionalização (i18n) no Padrão Boardbots.
Suporta Português (pt) e Inglês (en) para todo o ecossistema de interface,
regras do jogo, HUD, controles e manuais estratégicos dos 12 guerreiros.
"""

LANG_PT = "pt"
LANG_EN = "en"


def detect_system_lang() -> str:
    """Idioma da máquina: português se a interface do sistema estiver em português, senão inglês."""
    import locale
    import os
    import sys

    candidates = []
    override = os.environ.get("SAMURAI_EDGE_LANG", "").lower()
    if override in (LANG_PT, LANG_EN):
        return override
    if sys.platform == "win32":
        try:
            import ctypes
            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            return LANG_PT if (lang_id & 0x3FF) == 0x16 else LANG_EN
        except Exception:
            pass
    elif sys.platform == "darwin":
        try:
            import subprocess
            out = subprocess.run(["defaults", "read", "-g", "AppleLanguages"], capture_output=True, text=True, timeout=2).stdout
            langs = [line.strip(' ",()') for line in out.splitlines() if line.strip(' ,()')]
            if langs:
                candidates.append(langs[0])
        except Exception:
            pass
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        candidates.append(os.environ.get(var))
    try:
        candidates.append(locale.getlocale()[0])
    except Exception:
        pass
    for value in candidates:
        if value:
            return LANG_PT if value.lower().replace("-", "_").startswith("pt") else LANG_EN
    return LANG_EN


_current_lang = detect_system_lang()

def get_lang() -> str:
    return _current_lang

def set_lang(lang: str):
    global _current_lang
    if lang in (LANG_PT, LANG_EN):
        _current_lang = lang

def toggle_lang() -> str:
    global _current_lang
    _current_lang = LANG_EN if _current_lang == LANG_PT else LANG_PT
    return _current_lang

def t(key: str, **kwargs) -> str:
    """Retorna o texto localizado para a chave solicitada."""
    lang_dict = I18N.get(_current_lang, I18N[LANG_PT])
    text = lang_dict.get(key, I18N[LANG_PT].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text

